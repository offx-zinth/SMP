#!/usr/bin/env python
"""SMP MCP launcher — the entrypoint every agent harness calls.

Generated by ``install.sh`` into ``~/.smp/lib/smp-mcp-launcher.py`` and
executed through ``~/.local/bin/smp-mcp``.

What it does:

1. Resolves the *project root* (git toplevel, else the cwd the harness used
   to spawn the server).
2. Ensures ``<root>/.smp/graph.smpg`` exists — on first use it ingests the
   repo automatically (set ``SMP_AUTO_INGEST=0`` to disable).
3. Starts the MCP server over stdio on that graph.

``SMP_GRAPH_PATH`` overrides the graph location (absolute, or relative to
the project root).
"""

from __future__ import annotations

import asyncio
import os
import subprocess
import sys


def project_root() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            timeout=10,
        )
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass
    return os.getcwd()


def main() -> None:
    root = project_root()
    override = os.environ.get("SMP_GRAPH_PATH")
    if override:
        graph = override if os.path.isabs(override) else os.path.join(root, override)
    else:
        graph = os.path.join(root, ".smp", "graph.smpg")

    if not os.path.exists(graph) and os.environ.get("SMP_AUTO_INGEST", "1") != "0":
        print(f"smp-mcp: no graph at {graph}, ingesting {root} first...", file=sys.stderr)
        try:
            from smp.cli import ingest_directory

            stats = asyncio.run(ingest_directory(root, graph_path=graph))
            print(
                f"smp-mcp: ingested {stats['files']} files, {stats['nodes']} nodes, {stats['errors']} errors",
                file=sys.stderr,
            )
        except Exception as exc:  # keep serving with an empty graph
            print(f"smp-mcp: auto-ingest failed ({exc}); serving empty graph", file=sys.stderr)

    os.environ["SMP_GRAPH_PATH"] = graph
    os.chdir(root)

    from smp.protocol.mcp import main as mcp_main

    mcp_main()


if __name__ == "__main__":
    main()
